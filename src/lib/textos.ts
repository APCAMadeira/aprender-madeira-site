// Nomes dos grandes temas noutras línguas (até haver traduções no Directus).
const TEMAS: Record<string, { en: string; es: string }> = {
  'História e Instituições': { en: 'History and Institutions', es: 'Historia e Instituciones' },
  'Economia e Sociedade': { en: 'Economy and Society', es: 'Economía y Sociedad' },
  'Madeira e o Mundo': { en: 'Madeira and the World', es: 'Madeira y el Mundo' },
  'Religião, Tradições e Língua': { en: 'Religion, Traditions and Language', es: 'Religión, Tradiciones y Lengua' },
  'Artes e Letras': { en: 'Arts and Letters', es: 'Artes y Letras' },
  'Património e Território': { en: 'Heritage and Territory', es: 'Patrimonio y Territorio' },
  'Natureza e Ciências': { en: 'Nature and Sciences', es: 'Naturaleza y Ciencias' },
};
export function nomeTema(nome: string, l: Lingua): string {
  return l === 'pt' ? nome : (TEMAS[nome]?.[l] ?? nome);
}

export function formatarNumero(n: number, l: Lingua): string {
  return String(n).replace(/\B(?=(\d{3})+(?!\d))/g, l === 'en' ? ',' : ' ');
}

export function formatarData(iso: string | null | undefined, l: Lingua): string {
  if (!iso) return '';
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return '';
  return new Intl.DateTimeFormat(CODIGO_HTML[l], { day: 'numeric', month: 'long', year: 'numeric' }).format(d);
}
